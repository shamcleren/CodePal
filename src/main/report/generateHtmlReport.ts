function esc(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

function fmtTokens(n: number): string {
  if (n >= 1_000_000) return `${(n / 1_000_000).toFixed(1)}M`;
  if (n >= 1_000) return `${(n / 1_000).toFixed(1)}K`;
  return String(n);
}

function fmtCost(usd: number, locale: ResolvedLocale = "en"): string {
  return locale === "zh-CN" ? `US$${usd.toFixed(2)}` : `$${usd.toFixed(2)}`;
}

function fmtHeroCost(usd: number, locale: ResolvedLocale = "en"): string {
  if (usd > 0 && usd < 1) {
    return locale === "zh-CN" ? "<US$1" : "<$1";
  }
  const rounded = Math.round(usd);
  return locale === "zh-CN" ? `US$${rounded}` : `$${rounded}`;
}

function fmtHeroTokens(n: number): string {
  if (n >= 1_000_000) return `${Math.round(n / 1_000_000)}M`;
  if (n >= 1_000) return `${Math.round(n / 1_000)}K`;
  return String(Math.round(n));
}

function contextPercent(context: UsageContext | undefined): number | null {
  if (!context) return null;
  const percent =
    typeof context.percent === "number"
      ? context.percent
      : typeof context.used === "number" && typeof context.max === "number" && context.max > 0
        ? (context.used / context.max) * 100
        : undefined;
  return typeof percent === "number" && Number.isFinite(percent)
    ? Math.max(0, Math.round(percent))
    : null;
}

function contextTone(percent: number): "normal" | "notice" | "warning" | "danger" {
  if (percent >= 95) return "danger";
  if (percent >= 85) return "warning";
  if (percent >= 70) return "notice";
  return "normal";
}

function contextDetail(context: UsageContext | undefined): string {
  if (typeof context?.used !== "number" || typeof context.max !== "number") {
    return "";
  }
  return `${fmtTokens(context.used)} / ${fmtTokens(context.max)}`;
}

function fmtDateTime(ms: number, locale: ResolvedLocale = "en"): string {
  return new Intl.DateTimeFormat(locale, {
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
  }).format(new Date(ms));
}

function shortSessionId(sessionId: string): string {
  return sessionId.length > 18 ? `${sessionId.slice(0, 8)}…${sessionId.slice(-4)}` : sessionId;
}

function interpolate(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{([^}]+)\}/g, (_match, key: string) =>
    String(values[key] ?? ""),
  );
}

function statusLabel(status: string, copy: ReportCopy): string {
  return copy.status[status] ?? (status === "unknown" ? copy.usageOnly : status);
}

function estimateCost(
  stats: { inputTokens: number; outputTokens: number; cacheReadTokens: number; cacheCreationTokens: number },
  pricing: ModelPricing[],
  model?: string,
): number {
  const match = (model
    ? resolveModelPricing({ model }, pricing, { allowModelFallback: false })
    : undefined) ?? resolveModelPricing({ model: "claude-sonnet-4-5-20250929" }, pricing, {
      allowModelFallback: false,
    });
  if (!match) return 0;
  return estimateTokenCost(
    {
      ...stats,
      model: match.pricing.modelId,
    },
    [match.pricing],
    { allowModelFallback: false },
  ) ?? 0;
}

