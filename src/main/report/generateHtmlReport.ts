function reportTrendScript(): string {
  return `<script>
(() => {
  window.CodePalReportTrend = true;
  const formatNumber = (value) => {
    const number = Number(value || 0);
    if (number >= 1000000) return (number / 1000000).toFixed(1) + "M";
    if (number >= 1000) return (number / 1000).toFixed(1) + "K";
    return String(Math.round(number));
  };
  for (const chart of document.querySelectorAll("[data-report-trend]")) {
    const tooltip = chart.querySelector(".report-trend__tooltip");
    if (!tooltip) continue;
    const metric = chart.dataset.metric || "tokens";
    const metricLabel = chart.dataset.metricLabel || "Total";
    const labelTotal = chart.dataset.labelTotal || "Total";
    const labelInput = chart.dataset.labelInput || "Input";
    const labelOutput = chart.dataset.labelOutput || "Output";
    const labelCache = chart.dataset.labelCache || "Cache";
    const labelRequests = chart.dataset.labelRequests || "Requests";
    for (const zone of chart.querySelectorAll(".report-trend__hover-zone")) {
      zone.addEventListener("mouseenter", () => {
        let rows = '<div class="report-trend__tooltip-row"><span>' + metricLabel + '</span><strong>' + (zone.dataset.value || formatNumber(zone.dataset.total)) + '</strong></div>';
        if (metric === "tokens") {
          rows = '<div class="report-trend__tooltip-row"><span>' + labelTotal + '</span><strong>' + formatNumber(zone.dataset.total) + '</strong></div>' +
            '<div class="report-trend__tooltip-row"><span>' + labelInput + '</span><strong>' + formatNumber(zone.dataset.input) + '</strong></div>' +
            '<div class="report-trend__tooltip-row"><span>' + labelOutput + '</span><strong>' + formatNumber(zone.dataset.output) + '</strong></div>' +
            '<div class="report-trend__tooltip-row"><span>' + labelCache + '</span><strong>' + formatNumber(zone.dataset.cache) + '</strong></div>';
        }
        rows += '<div class="report-trend__tooltip-row"><span>' + labelRequests + '</span><strong>' + formatNumber(zone.dataset.requests) + '</strong></div>';
        tooltip.innerHTML = '<div class="report-trend__tooltip-title">' + zone.dataset.title + '</div>' + rows;
        tooltip.setAttribute("aria-hidden", "false");
        tooltip.classList.add("report-trend__tooltip--visible");
      });
      zone.addEventListener("mousemove", (event) => {
        const bounds = chart.getBoundingClientRect();
        const tooltipWidth = tooltip.offsetWidth || 190;
        const left = Math.min(bounds.width - tooltipWidth - 12, Math.max(12, event.clientX - bounds.left + 14));
        const top = Math.max(12, event.clientY - bounds.top - 110);
        tooltip.style.left = left + "px";
        tooltip.style.top = top + "px";
      });
      zone.addEventListener("mouseleave", () => {
        tooltip.classList.remove("report-trend__tooltip--visible");
        tooltip.setAttribute("aria-hidden", "true");
      });
    }
  }
})();
</script>`;
}

